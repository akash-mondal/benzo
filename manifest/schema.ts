export type Manifest = {
  version: 1; network: "test"; auction_id: string; escrow_ua: string; frost_group_key: string;
  lot?: string; supply: number; reserve_zats: string; tick_zats: string; B_max_zats: string;
  q_max: number; C_zats: string; fee_zats: string; deposit_addresses: string[];
  drand: typeof QUICKNET & { R: number }; T_submit: number; T_freeze: number; confirmations: 10;
  clearing: { mode: "uniform" | "vickrey"; band: "floor_pro_rata_units"; dust: "ascending_leaf_index"; tie: "ascending_leaf_index"; minimum_fill: number };
  refund: { invalid: "full_C" | "C_minus_fee"; reorg: "C_minus_fee_remove_leaf"; cancel: "full_C" };
  freeze: "merkle_root_v1";
  // Optional since Phase 5 (R4 item 2): SHA-256 of the signed witness-set side-packet, so the set is committed to
  // by the signed manifest and cannot be removed from a public directory unnoticed. See witness/witnessSetHash.
  witness_set_hash?: string;
  // R7 item 2: the three custody signers' X25519 envelope public keys, each generated by its own signer and
  // pinned here by the signed manifest, so a bidder's settlement envelope is sealed only to authenticated keys
  // (Reviewer R F-2 = Reviewer G G4). The product flow requires this field; the private halves never leave the
  // signers' own state dirs.
  envelope_keys?: string[];
  // Optional since PHASE-5 §11 gate CF: bond-then-pay (C is a bond of bond_bps bps of the cap; the winner's
  // balance is paid in a window of balance_window_blocks), a tlock-sealed price bound (reserve floor / max price)
  // opened at R, multi-lot rounds (orders bind one lot id; each lot clears independently), and recurring-round
  // linkage (series id, round index, previous round's result hash).
  // R33 items 1-2: the balance window and the balance addresses are fixed HERE, in the signed manifest, before
  // bidding — never chosen by the operator after the clear. deposit slot i pays its balance to
  // balance_addresses[i]; the window is (balance_window_start_height, balance_window_start_height +
  // balance_window_blocks] and its start block's header time is at or after R (winners learn they won first).
  bond?: { bond_bps: number; balance_window_blocks: number; balance_addresses: string[]; balance_window_start_height: number };
  sealed_reserve?: string;
  lots?: string[];
  serials?: { first: number; count: number; seed_round_offset: number };
  series?: { series_id: string; round_index: number; previous_result_hash: string | null };
};
export type Signed = { bytes: string; sha256: string; signer: string; signature: string };
export const hash = (bytes: Uint8Array | string) => createHash("sha256").update(bytes).digest("hex");
export const requireThat = (ok: unknown, reason: string): void => { if (!ok) throw new Error(`refused: ${reason}`); };

export function canonical(value: any): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value !== null && typeof value === "object")
    return `{${Object.keys(value).sort().map(k => `${JSON.stringify(k)}:${canonical(value[k])}`).join(",")}}`;
  requireThat(value !== undefined && (typeof value !== "number" || Number.isFinite(value)), "non-JSON value");
  return JSON.stringify(value);
}
export const jsonBytes = (value: unknown) => Buffer.from(canonical(value) + "\n");
export function zats(value: unknown, name: string): bigint {
  requireThat(typeof value === "string" && /^(0|[1-9][0-9]*)$/.test(value), `${name} must be decimal zatoshis`);
  const n = BigInt(value as string);
  requireThat(n <= 2_100_000_000_000_000n, `${name} exceeds money range`);
  return n;
}
function integer(n: unknown, name: string, min = 1, max = 2 ** 32 - 1) {
  requireThat(Number.isSafeInteger(n) && (n as number) >= min && (n as number) <= max, `${name} is out of range`);
}
function keys(object: any, expected: string) {
  requireThat(object && typeof object === "object" && !Array.isArray(object), "expected object");
  requireThat(Object.keys(object).sort().join(",") === expected.split(" ").sort().join(","), "unknown or missing manifest field");
}
// G-7 (mainnet readiness): the manifest's own network decides the address shape (testnet `utest1…`, mainnet
// `u1…`). This pure matcher keeps the offline verifier free of the classifier binary; the Node boundaries add
// the audited `benzo-pczt classify-address` check (envelope/destination.ts isUnifiedOn). The `network: "test"`
// lock below stays until the head lifts it.
export const uaShape = (addr: unknown, network: string): boolean =>
  typeof addr === "string" && (network === "main" ? /^u1[0-9a-z]+$/ : /^utest1[a-z0-9]+$/).test(addr);

// R33 item 1 (P1-2): the bond-then-pay balance addresses are manifest-fixed before bidding. Same length as
// deposit_addresses (deposit slot i pays its balance to balance_addresses[i]), distinct, UA shape on the manifest
// network, and disjoint from deposit_addresses, escrow_ua and any treasury funding_ua/treasury_ua (P1-1: a stale
// or pre-funded address must never be one whose earlier notes could pass for a balance payment). Mode clients that
// strip their own block before the base rules call this again with the full manifest (clear/market.ts).
export function checkBalanceAddresses(m: any): void {
  requireThat(m.bond !== undefined && Array.isArray(m.bond.balance_addresses), "balance addresses");
  const bal: unknown[] = m.bond.balance_addresses;
  requireThat(bal.length === m.deposit_addresses.length && bal.every(a => uaShape(a, m.network)) &&
    new Set(bal).size === bal.length, "balance addresses");
  const excluded = new Set<string>([m.escrow_ua, ...m.deposit_addresses]);
  for (const block of [m.buyback, m.rfq]) for (const f of [block?.funding_ua, block?.treasury_ua]) if (typeof f === "string") excluded.add(f);
  requireThat(bal.every(a => typeof a === "string" && !excluded.has(a)), "balance address is a deposit, escrow or treasury address");
}

export function validateManifest(m: Manifest): void {
  requireThat(m.witness_set_hash === undefined || (typeof m.witness_set_hash === "string" && /^[0-9a-f]{64}$/.test(m.witness_set_hash)), "witness_set_hash");
  requireThat(m.envelope_keys === undefined || (Array.isArray(m.envelope_keys) && m.envelope_keys.length === 3 &&
    m.envelope_keys.every(k => typeof k === "string" && /^[0-9a-f]{64}$/.test(k)) && new Set(m.envelope_keys).size === 3), "envelope_keys");
  requireThat(m.bond === undefined || (m.bond && typeof m.bond === "object" && !Array.isArray(m.bond) &&
    Object.keys(m.bond).sort().join(",") === "balance_addresses,balance_window_blocks,balance_window_start_height,bond_bps" &&
    Number.isSafeInteger(m.bond.bond_bps) && m.bond.bond_bps >= 1 && m.bond.bond_bps <= 10000 &&
    Number.isSafeInteger(m.bond.balance_window_blocks) && m.bond.balance_window_blocks >= 1 &&
    Number.isSafeInteger(m.bond.balance_window_start_height) && m.bond.balance_window_start_height >= 1), "bond");
  requireThat(m.sealed_reserve === undefined || (typeof m.sealed_reserve === "string" &&
    /^[0-9a-f]+$/.test(m.sealed_reserve) && m.sealed_reserve.length % 2 === 0 &&
    m.sealed_reserve.length >= 96 && m.sealed_reserve.length <= 4096), "sealed_reserve");
  requireThat(m.lots === undefined || (Array.isArray(m.lots) && m.lots.length >= 2 &&
    m.lots.every(l => /^[0-9a-f]{64}$/.test(l)) && new Set(m.lots).size === m.lots.length), "lots");
  requireThat(m.series === undefined || (m.series && typeof m.series === "object" && !Array.isArray(m.series) &&
    Object.keys(m.series).sort().join(",") === "previous_result_hash,round_index,series_id" &&
    /^[0-9a-f]{64}$/.test(m.series.series_id) && Number.isSafeInteger(m.series.round_index) && m.series.round_index >= 1 &&
    (m.series.previous_result_hash === null
      ? m.series.round_index === 1
      : m.series.round_index > 1 && /^[0-9a-f]{64}$/.test(m.series.previous_result_hash))), "series");
  if (m.serials !== undefined) {
    keys(m.serials, "first count seed_round_offset");
    integer(m.serials.first, "serial first", 0); integer(m.serials.count, "serial count");
    integer(m.serials.seed_round_offset, "serial seed offset");
    requireThat(m.clearing.mode === "uniform" && m.lots !== undefined, "serials require multi-lot uniform auction");
    requireThat(Number.isSafeInteger(m.serials.first + m.serials.count - 1) &&
      Number.isSafeInteger(m.drand.R + m.serials.seed_round_offset), "serial range/round overflow");
  }
  const base: Record<string, unknown> = { ...m };
  delete base.witness_set_hash; delete base.envelope_keys; delete base.bond; delete base.sealed_reserve; delete base.lots; delete base.series; delete base.serials;
  // Multi-lot rounds replace the single `lot` label with `lots` (field set recorded under Questions for Track A).
  keys(base, ["version","network","auction_id","escrow_ua","frost_group_key","supply","reserve_zats","tick_zats","B_max_zats","q_max","C_zats","fee_zats","deposit_addresses","drand","T_submit","T_freeze","confirmations","clearing","refund","freeze"].concat(m.lots === undefined ? ["lot"] : []).join(" "));
  requireThat(m.version === 1 && m.network === "test", "manifest version/network");
  requireThat(/^[0-9a-f]{64}$/.test(m.auction_id) && /^[0-9a-f]{64}$/.test(m.frost_group_key), "auction/group key");
  requireThat(m.lots !== undefined || (typeof m.lot === "string" && m.lot.length > 0 && m.lot.length <= 256), "lot");
  requireThat(uaShape(m.escrow_ua, m.network), "testnet escrow address");
  requireThat(Array.isArray(m.deposit_addresses) && m.deposit_addresses.length > 0 &&
    m.deposit_addresses.every(a => uaShape(a, m.network)) && new Set(m.deposit_addresses).size === m.deposit_addresses.length, "per-bid addresses");
  // R33 item 1: the balance addresses are fixed in the signed manifest before bidding — same length as
  // deposit_addresses (deposit slot i pays its balance to balance_addresses[i]), distinct, a UA on the manifest
  // network, and disjoint from the deposit/escrow/treasury addresses (a stale or pre-funded address can never be
  // one whose old notes could pass for a balance payment).
  if (m.bond !== undefined) checkBalanceAddresses(m as any);
  integer(m.supply, "supply"); integer(m.q_max, "q_max");
  const reserve = zats(m.reserve_zats, "reserve"), tick = zats(m.tick_zats, "tick"), cap = zats(m.B_max_zats, "B_max");
  const C = zats(m.C_zats, "C"), fee = zats(m.fee_zats, "fee");
  requireThat(tick > 0n && reserve <= cap && reserve % tick === 0n && cap % tick === 0n && fee < C, "collateral/caps/tick/fee");
  // Bond-then-pay (gate CF): C is the bond = bond_bps bps of the cap exactly (PHASE-5 §11 Decisions) and the
  // winner pays the balance in the window, so C need not cover the order. Without bond C covers the largest order.
  if (m.bond !== undefined) requireThat(C * 10000n === BigInt(m.bond.bond_bps) * cap, "bond C/cap");
  else requireThat(C >= BigInt(m.q_max) * cap + fee, "collateral/caps/tick/fee");
  keys(m.drand, "chain_hash public_key scheme genesis period R");
  for (const k of Object.keys(QUICKNET) as (keyof typeof QUICKNET)[])
    requireThat(m.drand[k] === QUICKNET[k], `quicknet ${k}`);
  integer(m.drand.R, "R", 1, Number.MAX_SAFE_INTEGER);
  integer(m.T_submit, "T_submit", 1, Number.MAX_SAFE_INTEGER); integer(m.T_freeze, "T_freeze", 1, Number.MAX_SAFE_INTEGER);
  requireThat(m.T_submit < m.T_freeze && m.T_freeze - m.T_submit >= 750 &&
    m.T_freeze < QUICKNET.genesis + (m.drand.R - 1) * QUICKNET.period, "submit/freeze/release ordering or confirmation buffer");
  requireThat(m.confirmations === 10 && m.freeze === "merkle_root_v1", "confirmations/freeze");
  keys(m.clearing, "mode band dust tie minimum_fill");
  requireThat(m.clearing.mode === "uniform" || (m.clearing.mode === "vickrey" && m.supply === 1), "clearing mode/supply");
  requireThat(m.clearing.band === "floor_pro_rata_units" && m.clearing.dust === "ascending_leaf_index" && m.clearing.tie === "ascending_leaf_index", "clearing rules");
  integer(m.clearing.minimum_fill, "minimum fill", 1, m.supply);
  keys(m.refund, "invalid reorg cancel");
  requireThat(["full_C","C_minus_fee"].includes(m.refund.invalid) && m.refund.reorg === "C_minus_fee_remove_leaf" && m.refund.cancel === "full_C", "refund policies");
}

// Both signing and verification use every canonical byte, including the exact drand round.
export function signingBytes(bytes: Buffer): Buffer { return bytes; }
export function signRecord(value: unknown, privatePem: string): Signed {
  const bytes = jsonBytes(value), key = createPrivateKey(privatePem);
  requireThat(key.asymmetricKeyType === "ed25519", "signer must be Ed25519");
  return { bytes: bytes.toString("base64"), sha256: hash(bytes), signer: createPublicKey(key).export({type:"spki",format:"der"}).toString("hex"),
    signature: sign(null, signingBytes(bytes), key).toString("hex") };
}
export function verifyRecord<T>(packet: Signed, trustedSigner: string): T {
  requireThat(packet && /^[0-9a-f]{88}$/.test(trustedSigner) && packet.signer === trustedSigner, "untrusted manifest/receipt signer");
  requireThat(typeof packet.bytes === "string" && /^[A-Za-z0-9+/]+={0,2}$/.test(packet.bytes), "manifest bytes");
  const bytes = Buffer.from(packet.bytes, "base64");
  requireThat(bytes.toString("base64") === packet.bytes && hash(bytes) === packet.sha256, "manifest byte hash");
  requireThat(/^[0-9a-f]{128}$/.test(packet.signature), "manifest signature length");
  const key = createPublicKey({key:Buffer.from(trustedSigner,"hex"),type:"spki",format:"der"});
  requireThat(key.asymmetricKeyType === "ed25519" && verify(null, signingBytes(bytes), key, Buffer.from(packet.signature,"hex")), "manifest signature");
  const value = JSON.parse(bytes.toString("utf8"));
  requireThat(jsonBytes(value).equals(bytes), "noncanonical manifest/receipt bytes");
  return value as T;
}
export function client(packet: Signed, trustedSigner: string) {
  const manifest = verifyRecord<Manifest>(packet, trustedSigner);
  validateManifest(manifest);
  return { manifest_hash: hash(Buffer.from(packet.bytes,"base64")), manifest };
}
